import pandas as pd
import matplotlib.pyplot as plt
import streamlit as st

st.set_page_config(page_title="Fertility Rate Tracker", layout="wide")

st.title("Fertility Rate Trends Across Select Countries and Regions")
st.write("Interactive visualization of average births per woman over time.")

# 1. Load Data
@st.cache_data
def load_data():
    # Adjust path if needed
    path = "API_SP.DYN.TFRT.IN_DS2_en_csv_v2_432495.csv"
    df = pd.read_csv(path, skiprows=4)
    df = df.drop(columns=["Indicator Name", "Indicator Code"])
    df = df.loc[:, ~df.columns.str.contains("^Unnamed")]

    df_long = pd.melt(
        df,
        id_vars=["Country Name", "Country Code"],
        var_name="Year",
        value_name="fertility_rate"
    )
    df_long["Year"] = df_long["Year"].astype(int)
    return df_long

df_long = load_data()

# 2. Country/Region Dictionary
codes = {
    'USA': 'U.S.A.',
    'FRA': 'France',
    'NOR': 'Norway',
    'HUN': 'Hungary',
    'CAN': 'Canada',
    'ISR': 'Israel',
    'MEX': 'Mexico',
    'EUU': 'E.U.',
    'AFE': 'Eastern & Southern Africa',
    'AFW': 'Central & Western Africa',
    'MEA': 'Middle East & North Africa',
    'EAS': 'East Asia & Pacific',
    'SAS': 'South Asia',
    'LCN': 'Latin America & Caribbean'
}

country_color = {
    'USA': '#34495E',
    'FRA': '#2980B9',
    'NOR': '#8E44AD',
    'HUN': '#E67E22',
    'CAN': '#E74C3C',
    'ISR': '#3498DB',
    'MEX': '#33FF57',
}

label_positions = {
    'USA': (1998, 1.8),
    'FRA': (1973, 2.3),
    'NOR': (1983, 1.4),
    'HUN': (2000, 1.2),
    'CAN': (2018, 1.1),
    'ISR': (2012, 3.2),
    'MEX': (1985, 3.5),
    'EUU': (1962, 2.0),
    'AFE': (2002, 5.1),
    'AFW': (1995, 6.2),
    'MEA': (1985, 5.2),
    'EAS': (1968, 4.1),
    'SAS': (1985, 4.3),
    'LCN': (1978, 3.8)
}

# 3. Interactive Sidebar Selection
st.sidebar.header("Filter Options")
selected_labels = st.sidebar.multiselect(
    "Select Countries / Regions to Display:",
    options=list(codes.values()),
    default=list(codes.values())
)

# Filter codes based on selection
selected_codes = {k: v for k, v in codes.items() if v in selected_labels}

# Filter DataFrame
df_subset = df_long[df_long['Country Code'].isin(selected_codes.keys())].copy()
df_subset['Country Name'] = df_subset['Country Code'].map(selected_codes)

# 4. Plotting
fig, axs = plt.subplots(figsize=(14, 7))
axs.grid(axis='y', color='lightgray', linewidth=0.7, zorder=0)

for code, label in selected_codes.items():
    line = df_subset[df_subset['Country Code'] == code].sort_values('Year')
    color = country_color.get(code, '#808080')

    alpha = 1.0 if code in country_color else 0.5
    linewidth = 2.5 if code in country_color else 1.5

    axs.plot(
        line['Year'],
        line['fertility_rate'],
        label=label,
        color=color,
        linewidth=linewidth,
        alpha=alpha,
    )

    if code in label_positions:
        x_pos, y_pos = label_positions[code]
        axs.text(
            x_pos,
            y_pos,
            label,
            color=color if code in country_color else "#666666",
            fontsize=9,
            fontweight="bold" if code in country_color else "normal",
            ha="center",
            va="center",
            bbox=dict(boxstyle="square,pad=0.15", facecolor="white", edgecolor="none", alpha=0.8)
        )

axs.set_xlim(1960, 2024)
axs.set_title(
    'The average number of children born to a woman in select countries and regions',
    fontsize=14,
    fontweight='bold',
    pad=25
)
axs.text(
    -0.05,
    1.0,
    "Children",
    transform=axs.transAxes,
    fontsize=11,
    ha="right",
    va="bottom",
)

plt.tight_layout()

# Display plot in Streamlit
st.pyplot(fig)